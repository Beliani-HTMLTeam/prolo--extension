export interface SendToSpamParams {
  usernameReg: string; // e.g., "Beliani FR" or "Beliani PT"
  shopId: number; // e.g., 7 for Beliani.fr
  newsletterId: number; // e.g., 43085
  newsletterSlug: string;
}

export async function sendToSpam(params: SendToSpamParams): Promise<Response> {
  const { usernameReg, shopId, newsletterId, newsletterSlug } = params;

  console.log('planning: ', params);
  

  // Build the form data
  const formData = new URLSearchParams();

  // if BENL or CHDE, then lang = "french" and lang_does = -1. If BEFR or CHFR then lang = "french" and lang_does = 1. For other shops, lang = "" and lang_does = 0

  // Hardcoded values
  formData.append('par[src][shop]', '1');
  formData.append('par[src][auction]', '1');
  formData.append('par[src][jour]', '0');
  formData.append('par[jour_topic_id][]', '0');

  if (newsletterSlug === 'BENL' || newsletterSlug === 'CHDE') {
    formData.append('par[lang]', 'french');
    formData.append('par[lang_does]', '-1');
  } else if (newsletterSlug === 'BEFR' || newsletterSlug === 'CHFR') {
    formData.append('par[lang]', 'french');
    formData.append('par[lang_does]', '1');
  } else {
    formData.append('par[lang]', '');
    formData.append('par[lang_does]', '0');
  }

  formData.append('par[username]', '');
  formData.append('par[username_reg]', usernameReg);
  formData.append('par[address_source][All]', '1');
  formData.append('par[address_source][System]', '1');
  formData.append('par[source_seller_w]', '');
  formData.append('par[article_id]', '');
  formData.append('par[sa]', '');
  formData.append('par[sa_old]', '0');
  formData.append('par[country_shipping]', '');
  formData.append('par[country_invoice]', '');
  formData.append('par[reseller]', '0');
  formData.append('par[no_sent]', '');
  formData.append('par[get_newsmail]', '0');
  formData.append('par[newsmail]', '3826');
  formData.append('par[unread_sign]', '0');
  formData.append('par[unread]', '0');
  formData.append('par[notsent]', '-1');
  formData.append('par[notsent_days]', '30');
  formData.append('par[unshipped]', '');
  formData.append('par[customer_type_ex]', '-1');
  formData.append('par[customer_type][]', '7');
  formData.append('par[customer_type_times]', '0');
  formData.append('par[items_per_page]', '20000');
  formData.append('par[shop_subscribed_do]', '1');
  formData.append('par[shop_subscribed]', shopId.toString());
  formData.append('par[sms_and_email]', '');
  formData.append('par[sms_shop_subscribed_do]', '');
  formData.append('par[sms_shop_subscribed]', shopId.toString());
  formData.append('par[is_mobile_phone]', '0');
  formData.append('par[phone_type]', 'billing');
  formData.append('par[ss_shop_id]', shopId.toString());
  formData.append('par[ssm_shop_id]', '');
  formData.append('par[is_not_opened_newsletter_checked]', '0');
  formData.append('par[not_opened_newsletter_days]', '');
  formData.append('par[is_not_visited_shop_checked]', '0');
  formData.append('par[not_visited_shop_days]', '');
  formData.append('par[resend_type]', 'html');
  formData.append('par[shop_id]', shopId.toString());
  formData.append('par[resend]', newsletterId.toString());
  formData.append('par[resend2]', '');
  formData.append('par[resend_ab_test]', '0');
  formData.append('show_table', 'false');

  // Make the POST request
  const response = await fetch('https://www.prologistics.info/api/customerSpam/sendToSpam/', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/x-www-form-urlencoded',
    },
    body: formData,
  });
  
  return response;
}
